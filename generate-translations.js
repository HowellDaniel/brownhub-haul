  keys.forEach(key => {
    if (transDict[key]) {
      newDict[key] = transDict[key];
    } else {
      // Keep English as fallback for untranslated strings
      newDict[key] = enData[key];
    }
  });
  
  const outputPath = path.join(i18nDir, `${code}.json`);
  fs.writeFileSync(outputPath, JSON.stringify(newDict, null, 2) + '\n', 'utf8');
